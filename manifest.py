# 升级制成就名（closer / duel_streak / hazard_tier）——渲染在秋烨，但解锁时消息需要名字
CLOSER_LEVELS = [
    (10, "色彩收尾人"),
    (7, "四阶收尾人"),
    (5, "三阶收尾人"),
    (3, "二阶收尾人"),
    (1, "一阶收尾人"),
]


def closer_level_name(progress):
    if progress <= 0:
        return "收尾人"
    for thr, name in CLOSER_LEVELS:
        if progress >= thr:
            return name
    return "收尾人"


def duel_streak_name(n):
    _CN = ["", "一", "二", "三", "四", "五", "六", "七", "八", "九", "十"]
    if n <= 0:
        return "连胜未开始"
    if n == 1:
        return "一破·卧龙出山"
    if n == 2:
        return "双连·一战成名"
    if n == 3:
        return "三连·举世皆惊"
    if n == 4:
        return "四连·天下无敌"
    if n >= 5:
        prefix = _CN[n] if n <= 10 else str(n)
        return f"{prefix}连·诛天灭地"
    return "一破·卧龙出山"


